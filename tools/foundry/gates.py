# Node types that do not survive glTF export. Blender's viewport renders them happily, which is
# exactly why this needs to be a gate: the failure is invisible until the GLB is in the browser.
GLTF_UNSAFE_NODES = {
    "ShaderNodeValToRGB",  # Color Ramp
    "ShaderNodeTexNoise",
    "ShaderNodeTexVoronoi",
    "ShaderNodeTexMusgrave",
    "ShaderNodeTexWave",
    "ShaderNodeTexMagic",
    "ShaderNodeTexChecker",
    "ShaderNodeTexGradient",
    "ShaderNodeBump",
    "ShaderNodeMixRGB",
    "ShaderNodeMath",
    "ShaderNodeVertexColor",
}


def g21_single_material_and_atlas(mesh_objs, max_atlas_px):
    materials = {m.name for o in mesh_objs for m in o.data.materials if m is not None}
    images = {}
    for name in materials:
        mat = bpy.data.materials.get(name)
        if not mat or not mat.use_nodes:
            continue
        for node in mat.node_tree.nodes:
            if node.type == "TEX_IMAGE" and node.image is not None:
                images[node.image.name] = tuple(node.image.size)
    oversized = {k: v for k, v in images.items() if max(v) > max_atlas_px}
    problems = []
    if len(materials) != 1:
        problems.append(f"{len(materials)} materials, expected exactly 1")
    if len(images) > 1:
        problems.append(f"{len(images)} textures, expected at most 1 atlas")
    if oversized:
        problems.append(f"textures exceed {max_atlas_px}px: {oversized}")
    return _result(
        "G21",
        not problems,
        "one material, one atlas within budget" if not problems else "; ".join(problems),
        materials=sorted(materials),
        textures={k: list(v) for k, v in images.items()},
        maxAtlasPx=max_atlas_px,
    )


def g22_materials_survive_gltf(mesh_objs):
    offenders = []
    for o in mesh_objs:
        for mat in o.data.materials:
            if mat is None or not mat.use_nodes:
                continue
            for node in mat.node_tree.nodes:
                if node.bl_idname in GLTF_UNSAFE_NODES:
                    offenders.append({"material": mat.name, "node": node.bl_idname, "label": node.name})
    return _result(
        "G22",
        not offenders,
        "all materials round-trip to glTF" if not offenders else f"{len(offenders)} nodes are lost on glTF export",
        offenders=offenders[:20],
        note="Blender's viewport renders these fine. The GLB will not.",
    )


