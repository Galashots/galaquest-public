def g11_t_pose(armature_obj):
    """HEURISTIC. No script can confirm a rest pose was intended as a T-pose.

    What it can confirm: bones whose names suggest upper arms point roughly along world X. That is
    reported as a heuristic in its own output so nobody quotes it as proof of a T-pose.
    """
    arm = armature_obj.data
    candidates = [
        b
        for b in arm.bones
        if any(t in b.name.lower() for t in ("upperarm", "upper_arm", "shoulder", "arm"))
        and "fore" not in b.name.lower()
    ]
    if not candidates:
        return _result(
            "G11", False, "no bone name suggests an upper arm, so the pose cannot be checked",
            heuristic=True,
        )
    detail = []
    passed = True
    for b in candidates:
        direction = (b.tail_local - b.head_local)
        if direction.length == 0:
            passed = False
            detail.append({"bone": b.name, "error": "zero-length bone"})
            continue
        direction.normalize()
        horizontality = abs(direction.dot(Vector((1.0, 0.0, 0.0))))
        detail.append({"bone": b.name, "alignmentToWorldX": round(horizontality, 4)})
        if horizontality < 0.85:
            passed = False
    return _result(
        "G11",
        passed,
        "arm bones are roughly horizontal" if passed else "arm bones are not horizontal",
        bones=detail,
        heuristic=True,
        note="A-pose deforms shoulders better than T-pose. T-pose is kept for retargeting; see QUALIFICATION.md.",
    )


def g12_root_bone(armature_obj):
    arm = armature_obj.data
    roots = [b for b in arm.bones if b.parent is None]
    problems = []
    if len(roots) != 1:
        problems.append(f"{len(roots)} root bones, expected exactly 1")
    root = roots[0] if roots else None
    if root is not None:
        if root.name != "Root":
            problems.append(f'root bone is named "{root.name}", expected "Root"')
        if root.head_local.length > 1e-6:
            problems.append(f"root head is at {tuple(round(c, 6) for c in root.head_local)}, not the origin")
    return _result(
        "G12",
        not problems,
        "single Root bone at the origin" if not problems else "; ".join(problems),
        rootNames=[b.name for b in roots],
    )


def g13_bone_layer_naming(armature_obj):
    bad = [b.name for b in armature_obj.data.bones if not b.name.startswith(BONE_LAYER_PREFIXES) and b.name != "Root"]
    return _result(
        "G13",
        not bad,
        "every bone carries a layer prefix"
        if not bad
        else f"{len(bad)} bones have no DEF_/CTRL_/MCH_ prefix",
        offenders=bad[:20],
    )


def g14_deform_joint_count(armature_obj, expected, region_share_note=""):
    """The contract pins rig.deformJointTarget. Nothing checked it until this gate existed."""
    deform = [b.name for b in armature_obj.data.bones if b.use_deform]
    passed = len(deform) == expected
    return _result(
        "G14",
        passed,
        f"{len(deform)} deform bones, contract expects {expected}",
        deformBones=sorted(deform),
        expected=expected,
        regionShareNote=region_share_note,
    )


def g15_deform_flag_set(armature_obj):
    """A DEF_ bone without the deform flag leaves its vertices unanimated and silently orphaned."""
    bad = [b.name for b in armature_obj.data.bones if b.name.startswith("DEF_") and not b.use_deform]
    also = [b.name for b in armature_obj.data.bones if not b.name.startswith("DEF_") and b.use_deform]
    problems = {}
    if bad:
        problems["defBonesWithoutDeformFlag"] = bad[:20]
    if also:
        problems["nonDefBonesWithDeformFlag"] = also[:20]
    return _result(
        "G15",
        not problems,
        "deform flags match the DEF_ prefix" if not problems else "deform flags disagree with naming",
        **problems,
    )


def g16_unit_armature_scale(armature_obj):
    s = armature_obj.scale
    off = [round(v, 6) for v in s if abs(v - 1.0) > 1e-6]
    return _result(
        "G16",
        not off,
        "armature scale is unit" if not off else f"armature scale is {tuple(round(v, 6) for v in s)}",
        scale=[round(v, 6) for v in s],
    )


def _vertex_weights(mesh_obj, armature_obj):
    """Per-vertex (name, weight) pairs, counting only groups that correspond to deform bones."""
    deform_names = {b.name for b in armature_obj.data.bones if b.use_deform}
    idx_to_name = {g.index: g.name for g in mesh_obj.vertex_groups}
    per_vert = []
    for v in mesh_obj.data.vertices:
        pairs = [
            (idx_to_name[g.group], g.weight)
            for g in v.groups
            if idx_to_name.get(g.group) in deform_names and g.weight > 0.0
        ]
        per_vert.append(pairs)
    return per_vert


def g17_no_zero_weight_verts(mesh_obj, armature_obj):
    per_vert = _vertex_weights(mesh_obj, armature_obj)
    bad = [i for i, pairs in enumerate(per_vert) if not pairs]
    return _result(
        "G17",
        not bad,
        "every vertex is weighted" if not bad else f"{len(bad)} vertices have no weight at all",
        verts=bad[:20],
    )


def g18_influence_cap(mesh_obj, armature_obj):
    per_vert = _vertex_weights(mesh_obj, armature_obj)
    over = [(i, len(pairs)) for i, pairs in enumerate(per_vert) if len(pairs) > MAX_INFLUENCES]
    worst = max((n for _, n in over), default=max((len(p) for p in per_vert), default=0))
    return _result(
        "G18",
        not over,
        f"max {worst} influences per vertex, cap is {MAX_INFLUENCES}",
        cap=MAX_INFLUENCES,
        maxObserved=worst,
        offenders=[{"vert": i, "influences": n} for i, n in over[:20]],
        note="Three.js drops the fifth influence silently. This gate is the only thing that notices.",
    )


def g19_weights_normalised(mesh_obj, armature_obj):
    per_vert = _vertex_weights(mesh_obj, armature_obj)
    bad = []
    for i, pairs in enumerate(per_vert):
        if not pairs:
            continue  # G17's problem, not this one
        total = sum(w for _, w in pairs)
        if abs(total - 1.0) > WEIGHT_EPS:
            bad.append({"vert": i, "sum": round(total, 6)})
    return _result(
        "G19",
        not bad,
        "weights normalised" if not bad else f"{len(bad)} vertices have weights not summing to 1",
        epsilon=WEIGHT_EPS,
        offenders=bad[:20],
    )


def g20_names_exportable(objs):
    bad = []
    for o in objs:
        if not NAME_OK.match(o.name):
            bad.append(o.name)
        if o.type == "ARMATURE":
            bad += [b.name for b in o.data.bones if not NAME_OK.match(b.name)]
        if o.type == "MESH":
            bad += [g.name for g in o.vertex_groups if not NAME_OK.match(g.name)]
    return _result(
        "G20",
        not bad,
        "all names are export-safe" if not bad else f"{len(bad)} names contain special characters",
        offenders=bad[:20],
    )


